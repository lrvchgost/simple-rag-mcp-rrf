def sentence_stream(rng: random.Random, pools: list[str]) -> str:
    """Абзац: по предложению из двух разных пулов + один шаблонный слот-кадр."""
    first = rng.choice(POOLS[pools[0]])
    second = rng.choice(POOLS[pools[1 % len(pools)]])
    a, b = rng.sample(SLOTS, 2)
    templated = rng.choice(TEMPLATES)[2].format(a=a, b=b)
    return " ".join((first, second, templated))


def make_chapter(rng: random.Random, vol_id: int, vol_title: str, year: int,
                 pools: list[str], chapter_no: int, target_bytes: int) -> str:
    title = rng.choice(SUBTITLES)
    parts: list[str] = [
        f"# Том {vol_id}. «{vol_title}» ({year})\n",
        f"## Глава {chapter_no}: {title}\n",
        f"Синтетическая глава тома {vol_id} «{vol_title}» ({year}) для нагрузочного "
        "тестирования RAG-поиска: повествование собрано из характерных мотивов цикла.\n",
    ]
    size = sum(len(p.encode("utf-8")) for p in parts)
    i = 0
    while size < target_bytes:
        paragraph = sentence_stream(rng, pools)
        parts.append(paragraph + "\n")
        size += len(paragraph.encode("utf-8")) + 1
        i += 1
        if i % 7 == 0:  # разделитель-отступ, как между эпизодами
            parts.append("\n---\n")
            size += 5
    return "\n".join(parts)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rng = random.Random(SEED)
    chapters_per_volume = 4
    static_bytes = sum(
        p.stat().st_size for p in (OUT_DIR.parent).glob("*") if p.is_file()
    )
    chapters_total = len(VOLUMES) * chapters_per_volume
    budget_bytes = TARGET_TOTAL_KB * 1024 - static_bytes
    target_chapter = budget_bytes // chapters_total

    written = 0
    for vol_id, vol_title, year, pools in VOLUMES:
        for ch in range(1, chapters_per_volume + 1):
            text = make_chapter(rng, vol_id, vol_title, year, pools, ch, target_chapter)
            path = OUT_DIR / f"tom{vol_id}_glava{ch}.md"
            path.write_text(text, encoding="utf-8")
            written += len(text.encode("utf-8"))
    print(f"written: {written / 1024:.0f} KB in {chapters_total} chapters -> {OUT_DIR}")


if __name__ == "__main__":
    main()
